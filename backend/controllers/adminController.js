// API to edit doctor details for admin panel
const editDoctor = async (req, res) => {
    try {
        const { docId, name, speciality, degree, experience, about, fees, available } = req.body
        const imageFile = req.file

        const updateData = {
            name,
            speciality,
            degree,
            experience,
            about,
            fees: Number(fees),
            available: available === 'true' || available === true
        }

        if (imageFile) {
            const imageUpload = await cloudinary.uploader.upload(imageFile.path, { resource_type: "image" })
            updateData.image = imageUpload.secure_url
        }

        await doctorModel.findByIdAndUpdate(docId, updateData)
        res.json({ success: true, message: 'Doctor Profile Updated Successfully' })
    } catch (error) {
        console.log(error)
        res.json({ success: false, message: error.message })
    }
}

// API to mark appointment completed for admin panel
const appointmentCompleteAdmin = async (req, res) => {
    try {
        const { appointmentId } = req.body
        const appointmentData = await appointmentModel.findById(appointmentId)
        if (!appointmentData) {
            return res.json({ success: false, message: 'Appointment not found' })
        }
        await appointmentModel.findByIdAndUpdate(appointmentId, { isCompleted: true })
        res.json({ success: true, message: 'Appointment Completed' })
    } catch (error) {
        console.log(error)
        res.json({ success: false, message: error.message })
    }
}

